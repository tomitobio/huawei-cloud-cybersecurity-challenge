const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('hcc_lang') : null;

void i18n.use(initReactI18next).init({
  resources,
  lng: stored ?? 'es',
  fallbackLng: 'es',
  interpolation: { escapeValue: false },
});

export function currentLang(): 'es' | 'en' {
  return (i18n.language === 'en' ? 'en' : 'es') as 'es' | 'en';
}

export function setLang(lang: 'es' | 'en') {
  void i18n.changeLanguage(lang);
  if (typeof localStorage !== 'undefined') localStorage.setItem('hcc_lang', lang);
}

export default i18n;
